/**
 * KST 기준 날짜 문자열(YYYY-MM-DD)이 KRX 휴장일인지 확인
 */
export function isKoreanMarketHoliday(kstDateStr: string): boolean {
  const parts = kstDateStr.split('-')
  const year = parseInt(parts[0])
  const md = `${parts[1]}-${parts[2]}`

  if (FIXED_HOLIDAYS.has(md)) return true

  const yearDates = YEAR_SPECIFIC[year]
  return yearDates ? yearDates.includes(md) : false
}
